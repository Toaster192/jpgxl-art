pub struct GalleryEntry {
    pub name: &'static str,
    pub program_text: &'static str,
}

/// Pair a display name with a `gallery/<file>` jxl-art program embedded at
/// compile time via `include_str!`. Every gallery preview renders at
/// `GALLERY_MAX_DIM` (see `prerender_gallery`), so there is no per-entry size.
macro_rules! gallery {
    ($($name:literal => $file:literal),* $(,)?) => {
        vec![$(
            GalleryEntry {
                name: $name,
                program_text: include_str!(concat!("../gallery/", $file)),
            }
        ),*]
    };
}

